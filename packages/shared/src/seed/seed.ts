/**
 * Genera fechas ISO relativas para la demo, asegurando que los filtros
 * temporales (últimas 24h, últimos 7 días, últimos 30 días) siempre devuelvan datos válidos.
 */
function recentDate(daysAgo: number, hoursAgo = 0): string {
  const d = new Date()
  d.setDate(d.getDate() - daysAgo)
  d.setHours(d.getHours() - hoursAgo, 0, 0, 0)
  return d.toISOString()
}

